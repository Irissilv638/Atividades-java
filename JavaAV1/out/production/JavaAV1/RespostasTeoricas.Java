
public class RespostasTeoricas {

    /*
     * QUESTÃO 5
     * O que é uma classe, um objeto, um atributo e um método?
     *
     * RESPOSTA:
     * Classe é um modelo usado para criar objetos.
     * Objeto é uma instância de uma classe.
     * Atributos são características de um objeto.
     * Métodos são ações que um objeto pode executar.
     */

    /*
     * QUESTÃO 12
     * O que é encapsulamento?
     *
     * RESPOSTA:
     * Encapsulamento é o princípio da programação
     * orientada a objetos que protege os atributos
     * de uma classe, geralmente utilizando private,
     * permitindo o acesso controlado por métodos.
     */

    /*
     * QUESTÃO 13
     * O que são getters e setters?
     *
     * RESPOSTA:
     * Getters são métodos utilizados para obter
     * os valores dos atributos. Setters são métodos
     * utilizados para modificar esses valores.
     */

    /*
     * QUESTÃO 14
     * Para que serve a palavra-chave this?
     *
     * RESPOSTA:
     * A palavra-chave this referencia o próprio
     * objeto. É utilizada para diferenciar os
     * atributos da classe dos parâmetros dos métodos.
     */

}
